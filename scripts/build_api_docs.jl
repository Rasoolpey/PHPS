# Writes the API reference, docs/api/*.md, from the docstrings of every exported name: one page per
# source folder, entries in source order, each with a link to its definition. Rerun after changing
# docstrings or exports:
#
#   julia --project=. scripts/build_api_docs.jl

using PHPS

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "docs", "api")

# page title and one-line summary per source folder, in reading order
const GROUPS = [
    "io" => ("Inputs and outputs", "Case and scenario loaders, JSON schemas, the parameter-expression reader, port contracts and the PowerFactory interface."),
    "network" => ("Network", "Bus ordering, Y-bus matrices, Norton stamps, load admittances and fault shunts."),
    "powerflow" => ("Power flow", "Newton-Raphson AC power flow."),
    "components" => ("Components (RMS)", "The component interface, the limiter primitives and the RMS models: machines, exciters, governors, loads, converters."),
    "assembly" => ("Assembly (RMS)", "Wiring, the DAE residual and its sparsity pattern."),
    "init" => ("Initialisation (RMS)", "Component initialisation from the power flow and the equilibrium of the full DAE."),
    "sim" => ("Simulation (RMS)", "BDF1 and IDA time integration, results writers and run records."),
    "phsim" => ("EMT simulator", "The port-Hamiltonian EMT model: system assembly, machines, exciters, steam and hydro units, converters, lines, transformers, motors, the zero-sequence network, fault clearing, the implicit midpoint integrator and the energy account."),
    "physical" => ("Physical steam and shaft models", "IAPWS-95 water and steam properties, the steam vessel, valve, turbine and rotor, and their composition with the machine and the grid."),
    "ph" => ("Port-Hamiltonian audits", "Storage functions, structure checks, port passivity, dissipativity, power balances and storage completion."),
    "roa" => ("Interval and certificate tools", "Interval arithmetic, enclosures, Taylor models, Lyapunov candidates, containment audits and certificate records."),
    "emdq" => ("Electromechanical dq models", "Reduced dq pilot models for stability analysis: network, AVR, phase-free forms and point-of-common-coupling views."),
]

relsrc(path) = replace(String(path), r"^.*?/src/" => "src/")
folder(rel) = (p = split(rel, '/'); length(p) >= 3 ? String(p[2]) : "core")

function docstring_text(d)
    s = join(string.(d.text))
    return strip(s, '\n')
end

# shift headings inside a docstring below the entry's own level (####)
demote(s) = replace(s, r"(?m)^(#{1,3}) " => s"####\1 ")

function entries()
    meta = Base.Docs.meta(PHPS)
    byf = Dict{String,Vector{Any}}()
    nodoc = Tuple{Symbol,String}[]
    for n in names(PHPS)
        n === :PHPS && continue
        b = Base.Docs.Binding(PHPS, n)
        if !haskey(meta, b)
            loc = try
                m = first(methods(getfield(PHPS, n))); r = relsrc(m.file); startswith(r, "src/") ? r * "#L" * string(m.line) : ""
            catch
                ""
            end
            push!(nodoc, (n, loc))
            continue
        end
        md = meta[b]
        docs = [md.docs[sig] for sig in md.order]
        d1 = first(docs)
        rel = relsrc(get(d1.data, :path, "?"))
        line = get(d1.data, :linenumber, 0)
        push!(get!(byf, folder(rel), Any[]), (; name = n, rel, line, docs))
    end
    return byf, nodoc
end

function write_page(io, key, title, summary, items)
    println(io, "# ", title, "\n")
    println(io, summary, " Source: [src/$key/](../../src/$key).\n")
    println(io, "Generated from the docstrings by `scripts/build_api_docs.jl`; do not edit by hand.\n")
    sort!(items; by = e -> (e.rel, e.line))
    println(io, "| Name | Defined in |\n|---|---|")
    for e in items
        println(io, "| [`", e.name, "`](#", lowercase(replace(string(e.name), r"[^A-Za-z0-9_-]" => "")), ") | `",
                replace(e.rel, "src/$key/" => ""), "` |")
    end
    println(io)
    for e in items
        println(io, "---\n\n### ", e.name, "\n")
        println(io, "*[", e.rel, ":", e.line, "](../../", e.rel, "#L", e.line, ")*\n")
        for (k, d) in enumerate(e.docs)
            k > 1 && println(io)
            println(io, demote(docstring_text(d)))
        end
        println(io)
    end
end

function main()
    mkpath(OUT)
    byf, nodoc = entries()
    known = Set(first.(GROUPS))
    extra = sort([k for k in keys(byf) if !(k in known)])
    groups = vcat(GROUPS, [k => (k, "Other exported names.") for k in extra])
    index = IOBuffer()
    println(index, "# API reference\n")
    println(index, "Every exported function and type of `PHPS`, with its docstring, grouped by source folder. ",
            "Generated by `julia --project=. scripts/build_api_docs.jl`; do not edit by hand.\n")
    println(index, "| Page | Names | What it covers |\n|---|---|---|")
    total = 0
    for (key, (title, summary)) in groups
        items = get(byf, key, Any[])
        isempty(items) && continue
        open(joinpath(OUT, key * ".md"), "w") do io
            write_page(io, key, title, summary, items)
        end
        total += length(items)
        println(index, "| [", title, "](", key, ".md) | ", length(items), " | ", summary, " |")
    end
    if !isempty(nodoc)
        println(index, "\nExported without a docstring (", length(nodoc), "): ",
                join(["`$n`" * (isempty(l) ? "" : " ([source](../../$l))") for (n, l) in sort(nodoc)], ", "), ".")
    end
    write(joinpath(OUT, "README.md"), take!(index))
    println("wrote ", total, " entries in ", count(k -> haskey(byf, first(k)), groups), " pages; ", length(nodoc),
            " exported names without a docstring")
end

main()
